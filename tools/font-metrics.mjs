// Measure the house fonts' glyph advances in a real browser and write
// docsync/metrics.py, the table docsync.compose paginates with.
//
//   node tools/font-metrics.mjs            (needs the network: Google Fonts)
//
// The composer used to guess every glyph at 0.54em (0.64 for capitals), so a
// 25-character headline in Barlow 800 counted as two lines and the hairline
// under it sat half an inch low, and body text ran a line long in five (the
// Wealth Tax report, 2026-11-09). These are the widths Chromium lays the same
// Google Fonts out with — the fonts every Appleseed template links — in ems,
// so they scale to any size. Kerning is left out, as it is a few hundredths
// of an em over a whole line.
import { chromium } from 'playwright';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const FONTS = 'https://fonts.googleapis.com/css2?family=Barlow:wght@400;700;800'
  + '&family=Source+Sans+3:ital,wght@0,400;0,700;1,400;1,700&display=swap';
const STYLES = [
  ['Barlow', 400, false], ['Barlow', 700, false], ['Barlow', 800, false],
  ['Source Sans 3', 400, false], ['Source Sans 3', 700, false],
  ['Source Sans 3', 400, true], ['Source Sans 3', 700, true],
];
let CHARS = '';
for (let c = 32; c < 127; c++) CHARS += String.fromCharCode(c);
CHARS += ' ʻ‘’“”—–…•·×½¢€£°§©®™āēīōūĀĒĪŌŪéèáíóúñüçÉÁÍÓÚÑÜ';

const browser = await chromium.launch();
const page = await browser.newPage();
await page.setContent(`<link rel="stylesheet" href="${FONTS}"><p>x</p>`, { waitUntil: 'networkidle' });
const table = await page.evaluate(async ({ styles, chars }) => {
  const out = {};
  const ctx = document.createElement('canvas').getContext('2d');
  for (const [family, weight, italic] of styles) {
    const spec = `${italic ? 'italic ' : ''}${weight} 1000px "${family}"`;
    await document.fonts.load(spec, chars);
    if (!document.fonts.check(spec, chars)) throw new Error('font did not load: ' + spec);
    ctx.font = spec;
    const adv = {};
    for (const ch of chars) adv[ch] = Math.round(ctx.measureText(ch).width) / 1000;
    out[`${family}|${weight}|${italic ? 'italic' : 'normal'}`] = adv;
  }
  return out;
}, { styles: STYLES, chars: CHARS });
await browser.close();

const here = path.dirname(fileURLToPath(import.meta.url));
const lines = ['"""Glyph advances of the house fonts, in ems — generated by',
  'tools/font-metrics.mjs from the Google Fonts every Appleseed template links,',
  'measured in Chromium. docsync.compose wraps words against these to paginate',
  'a document laid out from text. Regenerate; do not edit by hand."""', '',
  'ADV = {'];
for (const [key, adv] of Object.entries(table)) {
  lines.push(`    ${JSON.stringify(key)}: {`);
  const items = Object.entries(adv).map(([ch, w]) => `${JSON.stringify(ch)}: ${w}`);
  for (let i = 0; i < items.length; i += 8) lines.push('        ' + items.slice(i, i + 8).join(', ') + ',');
  lines.push('    },');
}
lines.push('}', '');
writeFileSync(path.join(here, '..', 'docsync', 'metrics.py'), lines.join('\n'));
console.log('wrote docsync/metrics.py:', Object.keys(table).join(', '));
